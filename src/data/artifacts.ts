function slugify(value: string) {
  return value
    .toLowerCase()
    .replaceAll("'", '')
    .replaceAll('&', 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function lightGgItemSource(name: string, hash: number | null): SourceLink {
  if (!hash) {
    return {
      label: 'Light.gg search',
      url: `https://www.light.gg/db/search/?q=${encodeURIComponent(name)}`,
    }
  }

  return {
    label: 'Light.gg artifact page',
    url: `https://www.light.gg/db/items/${hash}/${slugify(name)}/`,
  }
}

function buildSources(name: string, hash: number | null, extra: SourceLink[] = []): SourceLink[] {
  return [
    lightGgItemSource(name, hash),
    {
      label: 'Shacknews season order and dates',
      url: 'https://www.shacknews.com/article/119428/all-seasons-and-release-date-order-destiny-2',
    },
    {
      label: 'Bungie Manifest documentation',
      url: 'https://bungie-net.github.io/multi/operation_get_Destiny2-Manifest.html',
    },
    ...extra,
  ]
}

function mod(
  name: string,
  description: string,
  column: number,
  row: number,
  source: string,
  tags: Partial<ArtifactMod['tags']> = {},
): ArtifactMod {
  return {
    name,
    description,
    column,
    row,
    source,
    tags: {
      elements: tags.elements ?? [],
      weapons: tags.weapons ?? [],
      champions: tags.champions ?? [],
      subclasses: tags.subclasses ?? [],
      mechanics: tags.mechanics ?? [],
    },
  }
}

